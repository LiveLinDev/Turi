/* Índices, pesos y valores de los primeros 440 objetos en orden de densidad. */
static void add_item16(uint16_t *best, int capacity, int weight, int value) {
    __m512i added = _mm512_set1_epi16(value);
    int start = capacity - 31;
    for (; start >= weight; start -= 32) {
        __m512i skip = _mm512_loadu_si512(best + start);
        __m512i previous = _mm512_loadu_si512(best + start - weight);
        __m512i take = _mm512_add_epi16(previous, added);
        _mm512_storeu_si512(best + start, _mm512_max_epu16(skip, take));
    }
    for (int at = start + 31; at >= weight; at--) {
        int take = best[at - weight] + value;
        if (take > best[at]) best[at] = take;
    }
}

