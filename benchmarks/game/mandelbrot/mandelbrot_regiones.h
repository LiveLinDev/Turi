static uint64_t factor_of(unsigned bytes) {
    uint64_t base = 31, result = 1;
    for (; bytes; bytes >>= 1) {
        if (bytes & 1) result = result * base % 1000000007;
        base = base * base % 1000000007;
    }
    return result;
}

static uint64_t row(int n, double inverse, double imaginary, uint64_t *inside) {
    const uint64_t modulus = 1000000007;
    uint64_t checksum = 0;
    int x = 0;
    unsigned band = (unsigned)(fabs(imaginary) * REGION_RESOLUTION);
    if (band >= REGION_RESOLUTION) band = REGION_RESOLUTION - 1;
    unsigned run = zones[band], end = zones[band + 1];
    const double stride = 1.0 / REGION_RESOLUTION;
    while (x + 32 <= n) {
        const double left = x * inverse - 1.5, right = (x + 31) * inverse - 1.5;
        while (run < end && left >= zones[REGION_RESOLUTION + 2 + 3 * run] * stride - 1.5) ++run;
        if (run < end) {
            unsigned at = REGION_RESOLUTION + 1 + 3 * run;
            double begin = zones[at] * stride - 1.5, stop = zones[at + 1] * stride - 1.5;
            if (left >= begin && right <= stop) {
                int upto = (int)((stop + 1.5) / inverse) + 1;
                int blocks = ((n < upto ? n : upto) - x) / 32;
                if (blocks < 1) blocks = 1;
                while (blocks > 1 && (x + blocks * 32 - 1) * inverse - 1.5 > stop) --blocks;
                uint64_t factor = factor_of(4 * blocks), bytes = 0;
                if (zones[at + 2]) {
                    *inside += (uint64_t)(blocks * 32);
                    bytes = UINT64_C(255) * ((factor + 1000000006) * 233333335 % 1000000007);
                }
                checksum = (checksum * factor + bytes) % 1000000007;
                x += blocks * 32;
                continue;
            }
        }
        checksum = (checksum * 923521 + pixels(x, n, 4, inverse, imaginary, inside)) % modulus;
        x += 32;
    }
    for (; x < n; x += 8)
        checksum = (checksum * 31 + pixels(x, n, 1, inverse, imaginary, inside)) % modulus;
    return checksum;
}
